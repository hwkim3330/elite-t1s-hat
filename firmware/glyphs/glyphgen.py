#!/usr/bin/env python3
"""zone_glyphs.txt -> code: the LED panels' fonts, icons and colours as C (the zone controller) and Python (the
bench console), so the two renderers draw from one definition.

    python3 glyphgen.py [zone_glyphs.txt] [--c FILE] [--py FILE ...] [--check]

Defaults (relative to this folder): zone_glyphs.txt -> ../t1s_node/zone_glyphs.h. --py is written only when given
(the console keeps it). --check writes nothing and exits 1 if a target differs from what would be generated.

Source format (see the top of zone_glyphs.txt): `@color name r g b`, `@font name height`, then per glyph a line
":name" and exactly `height` rows of '#' / '.'. Outside a glyph, lines starting with '#' are comments.

Outputs
  C       zone_glyphs.h: ZG_<NAME> colours, per font a table of zg_glyph {name, w, h, rows[]} (bit x of rows[y] =
          column x), ZG_<FONT>_<GLYPH> pointers for the named ones, zg_find(), ZG_TEXT indexed by c - 32
  Python  COLORS {name: (r, g, b)}, FONTS {font: {name: (w, h, rows)}}, GLYPHS_HASH (the same as in C)
"""
import argparse
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))


def parse(path):
    colors, fonts, order = {}, {}, []
    font, h = None, 0
    lines = open(path).read().split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i].strip()
        i += 1
        if not ln or ln.startswith("#"):
            continue
        if ln.startswith("@color "):
            _, name, r, g, b = ln.split()
            colors[name] = tuple(int(v) for v in (r, g, b))
            assert all(0 <= v <= 255 for v in colors[name]), ln
        elif ln.startswith("@font "):
            _, font, hs = ln.split()
            h = int(hs)
            assert 1 <= h <= 16, ln
            fonts[font] = {}
            order.append(font)
        elif ln.startswith(":"):
            assert font, "glyph before @font: %s" % ln
            name = ln[1:]
            name = " " if name == "space" else name
            rows = [lines[i + k].strip() for k in range(h)]
            i += h
            w = len(rows[0])
            assert w <= 16 and all(len(r) == w and set(r) <= set("#.") for r in rows), "%s %r: bad rows" % (font, name)
            assert name not in fonts[font], "%s %r twice" % (font, name)
            fonts[font][name] = (w, h, [sum(1 << x for x, ch in enumerate(r) if ch == "#") for r in rows])
        else:
            raise SystemExit("%s:%d: cannot read %r" % (path, i, ln))
    if "text" in fonts:
        missing = [chr(c) for c in range(32, 127) if chr(c) not in fonts["text"]]
        assert not missing, "text font misses %r" % missing
    return colors, fonts, order


def digest(colors, fonts, order):
    return zlib.crc32(repr((sorted(colors.items()), [(f, sorted(fonts[f].items())) for f in order])).encode()) & 0xFFFFFFFF


def cname(s):
    return "".join(ch if ch.isalnum() else "_" for ch in s).upper()


def c_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def gen_c(colors, fonts, order, hsh):
    o = ["// Generated by firmware/glyphs/glyphgen.py from zone_glyphs.txt -- edit that file, not this one.",
         "// The LED panels' fonts, tell-tale icons and colours; the bench console draws from the same source.",
         "#pragma once", "#include <stdint.h>", "#include <string.h>", "",
         "#define ZG_GLYPHS_HASH 0x%08xu" % hsh, "",
         "typedef struct { const char *name; uint8_t w, h; uint16_t rows[16]; } zg_glyph;   // bit x of rows[y] = column x", ""]
    for n, (r, g, b) in colors.items():
        o.append("static const uint8_t ZG_%s[3] = {%d, %d, %d};" % (cname(n), r, g, b))
    o.append("")
    for f in order:
        gl = fonts[f]
        items = list(gl.items())
        if f == "text":
            items = [(chr(c), gl[chr(c)]) for c in range(32, 127)]
        o.append("#define ZG_%s_COUNT %d" % (cname(f), len(items)))
        o.append("static const zg_glyph ZG_%s[%d] = {" % (cname(f), len(items)))
        for name, (w, h, rows) in items:
            o.append("  {%s, %d, %d, {%s}}," % (c_str(name), w, h, ", ".join(str(r) for r in rows)))
        o.append("};")
        if f != "text":
            for k, (name, _) in enumerate(items):
                if len(name) > 1:
                    o.append("#define ZG_%s_%s (&ZG_%s[%d])" % (cname(f), cname(name), cname(f), k))
        o.append("")
    o += ["// a glyph of a font by name (one character for the letter fonts), or nullptr / NULL",
          "static inline const zg_glyph *zg_find(const zg_glyph *t, int n, const char *name) {",
          "  for (int i = 0; i < n; i++)",
          "    if (!strcmp(t[i].name, name)) return &t[i];",
          "  return 0;",
          "}",
          "static inline const zg_glyph *zg_text(char c) { return c >= 32 && c < 127 ? &ZG_TEXT[c - 32] : &ZG_TEXT['?' - 32]; }",
          ""]
    return "\n".join(o)


def gen_py(colors, fonts, order, hsh):
    o = ['"""Generated by elite-t1s-hat firmware/glyphs/glyphgen.py from zone_glyphs.txt -- edit that file, not this one.',
         "The LED panels' fonts, tell-tale icons and colours; the zone controller's C renderer draws from the same source.",
         "FONTS[font][name] = (width, height, rows), bit x of rows[y] = column x.\"\"\"", "",
         "GLYPHS_HASH = 0x%08x" % hsh, "", "COLORS = {"]
    for n, rgb in colors.items():
        o.append("    %r: %r," % (n, rgb))
    o += ["}", "", "FONTS = {"]
    for f in order:
        o.append("    %r: {" % f)
        for name, (w, h, rows) in fonts[f].items():
            o.append("        %r: (%d, %d, %r)," % (name, w, h, tuple(rows)))
        o.append("    },")
    o += ["}", ""]
    return "\n".join(o)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("src", nargs="?", default=os.path.join(HERE, "zone_glyphs.txt"))
    ap.add_argument("--c", default=os.path.join(HERE, "..", "t1s_node", "zone_glyphs.h"))
    ap.add_argument("--py", action="append", default=[])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    colors, fonts, order = parse(a.src)
    hsh = digest(colors, fonts, order)
    out = [(a.c, gen_c(colors, fonts, order, hsh))] + [(p, gen_py(colors, fonts, order, hsh)) for p in a.py]
    bad = 0
    for path, text in out:
        old = open(path).read() if os.path.exists(path) else None
        if a.check:
            if old != text:
                print("differs: %s" % path)
                bad += 1
        elif old != text:
            open(path, "w").write(text)
            print("wrote %s" % path)
    print("glyphs hash 0x%08x: %s" % (hsh, ", ".join("%s %d" % (f, len(fonts[f])) for f in order)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
